function highlightKnowledgeTerms(html, articleTerms = []) {
  const terms = [...new Set([...articleTerms, ...KNOWLEDGE_TERMS])]
    .filter(Boolean)
    .sort((a, b) => b.length - a.length);
  const pattern = new RegExp(`(${terms.map(term => term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})`, 'g');
  let count = 0;
  const seen = new Set();
  return html.split(/(<[^>]+>)/g).map(part => {
    if (!part || part.startsWith('<')) return part;
    return part.replace(pattern, term => {
      if (seen.has(term) || count >= 8) return term;
      seen.add(term);
      count += 1;
      const cls = count <= 2 ? 'term-highlight-yellow' : 'term-highlight';
      return `<span class="${cls}">${term}</span>`;
    });
  }).join('');
}

