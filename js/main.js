const KNOWLEDGE_TERM_PATTERN = new RegExp(`(${KNOWLEDGE_TERMS.map(term => term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})`, 'g');

function highlightKnowledgeTerms(html) {
  let count = 0;
  const seen = new Set();
  return html.split(/(<[^>]+>)/g).map(part => {
    if (!part || part.startsWith('<')) return part;
    return part.replace(KNOWLEDGE_TERM_PATTERN, term => {
      if (seen.has(term) || count >= 8) return term;
      seen.add(term);
      count += 1;
      return `<span class="term-highlight">${term}</span>`;
    });
  }).join('');
}

