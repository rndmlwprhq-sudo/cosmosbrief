function knowledgeArticle(title, summary, body, points, keywords, status = '임시 공개') {
  const extension = (KNOWLEDGE_ARTICLE_EXTENSIONS[title] || [])
    .map(paragraph => `<p>${paragraph}</p>`)
    .join('');
  const highlightTerms = [...keywords, ...(KNOWLEDGE_SUBTOPICS[title] || []), ...(KNOWLEDGE_EXTRA_HIGHLIGHTS[title] || [])];
  return {
    title,
    summary,
    teaser: `${summary} 이 질문을 따라 관측과 물리의 연결을 살펴보면, 익숙한 우주 용어가 다음 밤하늘을 읽는 단서로 바뀝니다.`,
    subtopics: KNOWLEDGE_SUBTOPICS[title] || [],
    tags: [{ cls: 'beginner', label: '입문' }, { cls: 'mission', label: status }],
    readTime: extension ? '9' : '7',
    difficulty: '입문',
    date: `2026 · ${status}`,
    body: `<div class="callout"><span class="callout-icon">한 줄 요약</span>${escapeHtml(summary)}</div>
      ${highlightKnowledgeTerms(body + extension, highlightTerms)}
      <div class="fact-box"><div class="fact-title">핵심 포인트</div><ul>${points.map(point => `<li>${escapeHtml(point)}</li>`).join('')}</ul></div>
      <div class="callout"><span class="callout-icon">관련 키워드</span>${keywords.map(keyword => escapeHtml(keyword)).join(' · ')}</div>`,
  };
}

function topicArticle(title, summary, paragraphs, points, keywords, status = '임시 공개') {
  return knowledgeArticle(
    title,
    summary,
    paragraphs.map(paragraph => `<p>${paragraph}</p>`).join(''),
    points,
    keywords,
    status
  );
}

