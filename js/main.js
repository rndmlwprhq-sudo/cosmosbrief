(function scrollReveal() {
  const targets = document.querySelectorAll('.reveal');
  if (!targets.length || !('IntersectionObserver' in window)) return;
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add('visible');
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -50px 0px' });
  targets.forEach(target => observer.observe(target));
})();

(function animateCounters() {
  const counters = document.querySelectorAll('.stat-number[data-target]');
  if (!counters.length || !('IntersectionObserver' in window)) return;
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      const el = entry.target;
      const target = Number(el.dataset.target || 0);
      const suffix = el.dataset.suffix || '';
      const start = performance.now();
      const duration = 1400;
      function tick(now) {
        const p = Math.min((now - start) / duration, 1);
        const eased = 1 - Math.pow(1 - p, 3);
        el.textContent = Math.round(target * eased) + suffix;
        if (p < 1) requestAnimationFrame(tick);
      }
      requestAnimationFrame(tick);
      observer.unobserve(el);
    });
  }, { threshold: 0.5 });
  counters.forEach(counter => observer.observe(counter));
})();

function storyBody(paragraphs, points, keywords, extraHtml = '') {
  return paragraphs.map(paragraph => `<p>${paragraph}</p>`).join('')
    + extraHtml
    + `<section class="story-points"><h3>핵심 포인트</h3><ul>${points.map(point => `<li>${escapeHtml(point)}</li>`).join('')}</ul></section>`
    + `<div class="story-keywords" aria-label="관련 키워드">${keywords.map(keyword => `<span class="story-keyword">${escapeHtml(keyword)}</span>`).join('')}</div>`;
}

